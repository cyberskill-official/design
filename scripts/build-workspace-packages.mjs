#!/usr/bin/env node
/**
 * Compile slim workspace packages. Runtime packs must not ship raw JSX,
 * templates, compiler runtimes, or _audit fixtures (enterprise audit P0/P2).
 */
import * as esbuild from "esbuild";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { BUNDLE_PATH, parseBundleHeader } from "./build-bundle.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function walk(dir, pred, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, pred, out);
    else if (pred(name, full)) out.push(full);
  }
  return out;
}

function resetDir(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}

async function transformTree(entryPoints, outdir, outbase) {
  await esbuild.build({
    entryPoints,
    outdir,
    outbase,
    bundle: false,
    format: "esm",
    jsx: "automatic",
    platform: "neutral",
    logLevel: "warning",
  });
}

async function bundleOne(entry, outfile) {
  await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: "esm",
    jsx: "automatic",
    platform: "neutral",
    external: ["react", "react-dom", "react/jsx-runtime", "react/jsx-dev-runtime"],
    logLevel: "warning",
  });
}

function writeIndex(pkgDir, lines) {
  writeFileSync(join(pkgDir, "index.js"), `${lines.join("\n")}\n`);
}

function copyDts(fromRel, destBase) {
  const from = join(root, fromRel);
  for (const file of walk(from, (n) => n.endsWith(".d.ts"))) {
    const rel = relative(from, file);
    const dest = join(destBase, fromRel, rel);
    mkdirSync(dirname(dest), { recursive: true });
    cpSync(file, dest);
  }
}

async function buildReact() {
  const dist = join(root, "packages/react/dist");
  resetDir(dist);
  const entries = walk(join(root, "components"), (n) => n.endsWith(".js") || n.endsWith(".jsx"));
  entries.push(join(root, "tokens/tokens.js"));
  await transformTree(entries, dist, root);
  for (const file of walk(dist, (n) => n.endsWith(".js"))) {
    const src = readFileSync(file, "utf8");
    const next = src.replace(/from\s+(["'])([^"']+)\.jsx\1/g, "from $1$2.js$1");
    if (next !== src) writeFileSync(file, next);
  }
  copyDts("components", dist);

  const header = parseBundleHeader(readFileSync(BUNDLE_PATH, "utf8"));
  const by = new Map();
  for (const c of header.components) {
    if (!by.has(c.sourcePath)) by.set(c.sourcePath, []);
    by.get(c.sourcePath).push(c.name);
  }
  const jsLines = [
    '"use client";',
    "// GENERATED by scripts/build-workspace-packages.mjs — compiled ESM, no raw JSX.",
  ];
  const dtsLines = ["// GENERATED by scripts/build-workspace-packages.mjs"];
  const seen = new Set();
  for (const sourcePath of [...by.keys()].sort()) {
    const names = by.get(sourcePath).filter((n) => !seen.has(n));
    for (const n of names) seen.add(n);
    if (!names.length) continue;
    const compiled = "./dist/" + sourcePath.replace(/\.jsx$/, ".js");
    const typesMod = "./dist/" + sourcePath.replace(/\.(jsx|js)$/, "");
    const typesFile = join(root, "packages/react", typesMod + ".d.ts");
    jsLines.push(`export { ${names.join(", ")} } from ${JSON.stringify(compiled)};`);
    const typed = names.filter((n) => !["CS_ICONS", "CS_LOGO_VIEWBOX", "CS_LOGO_MARK_INNER"].includes(n));
    if (typed.length && existsSync(typesFile)) {
      dtsLines.push(`export { ${typed.join(", ")} } from ${JSON.stringify(typesMod)};`);
      dtsLines.push(`export type * from ${JSON.stringify(typesMod)};`);
    }
  }
  writeIndex(join(root, "packages/react"), jsLines);
  writeFileSync(join(root, "packages/react/index.d.ts"), `${dtsLines.join("\n")}\n`);

  const pkgPath = join(root, "packages/react/package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const exports = {
    ".": { types: "./index.d.ts", import: "./index.js" },
    "./package.json": "./package.json",
  };
  const exported = new Set();
  for (const sourcePath of [...by.keys()].sort()) {
    const names = (by.get(sourcePath) || []).filter((n) => !["CS_ICONS", "CS_LOGO_VIEWBOX", "CS_LOGO_MARK_INNER"].includes(n));
    for (const name of names) {
      if (exported.has(name)) continue;
      exported.add(name);
      const key = "./" + name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
      const compiled = "./dist/" + sourcePath.replace(/\.jsx$/, ".js");
      const types = "./dist/" + sourcePath.replace(/\.(jsx|js)$/, ".d.ts");
      exports[key] = existsSync(join(root, "packages/react", types))
        ? { types, import: compiled }
        : { import: compiled };
    }
  }
  pkg.exports = exports;
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
}

function buildTokens() {
  const dist = join(root, "packages/tokens/dist");
  resetDir(dist);
  const tokensDir = join(root, "tokens");
  for (const name of readdirSync(tokensDir)) {
    const full = join(tokensDir, name);
    if (statSync(full).isDirectory()) continue;
    if (/\.(css|json|js|d\.ts)$/.test(name) || name.endsWith(".dtcg.json")) {
      cpSync(full, join(dist, name));
    }
  }
  cpSync(join(root, "base/high-contrast.css"), join(dist, "high-contrast.css"));
  cpSync(join(root, "base/scope.css"), join(dist, "scope.css"));
  writeFileSync(
    join(dist, "tokens.css"),
    [
      "/* Layered token runtime for @cyberskill/tokens/css. Generated by scripts/build-workspace-packages.mjs */",
      "@layer primitive, semantic, component, state;",
      '@import "./typography.css" layer(primitive);',
      '@import "./spacing.css" layer(primitive);',
      '@import "./motion.css" layer(primitive);',
      '@import "./elevation.css" layer(primitive);',
      '@import "./fonts.css" layer(primitive);',
      '@import "./colors.css" layer(semantic);',
      '@import "./elements.css" layer(semantic);',
      '@import "./theme-attributes.css" layer(semantic);',
      '@import "./component-tokens.css" layer(component);',
      '@import "./styles.css" layer(state);',
      "",
    ].join("\n"),
  );
  writeIndex(join(root, "packages/tokens"), [
    "export { tokens } from \"./dist/tokens.js\";",
    "export const packageName = \"@cyberskill/tokens\";",
    "export const source = \"./dist/tokens.dtcg.json\";",
    "export const layers = \"./dist/layers.json\";",
  ]);
}

async function buildThemes() {
  const dist = join(root, "packages/themes/dist");
  resetDir(dist);
  await bundleOne(join(root, "components/_theme/provider.js"), join(dist, "provider.js"));
  cpSync(join(root, "components/_theme/provider.d.ts"), join(dist, "provider.d.ts"));
  cpSync(join(root, "base/high-contrast.css"), join(dist, "high-contrast.css"));
  const seeds = JSON.parse(readFileSync(join(root, "tokens/element-seeds.json"), "utf8"));
  const packs = [];
  for (const [id, el] of Object.entries(seeds.elements || {})) {
    packs.push({ element: id, intensity: "soft", name: el.soft, label: el.label });
    packs.push({ element: id, intensity: "middle", name: el.middleName, label: el.label });
    packs.push({ element: id, intensity: "deep", name: el.deep, label: el.label });
  }
  writeFileSync(
    join(dist, "brand-packs.json"),
    JSON.stringify(
      {
        generatedBy: "scripts/build-workspace-packages.mjs",
        highContrast: "./high-contrast.css",
        styleAxis: "@cyberskill/tokens/css/style-axis",
        elementRuntime: "@cyberskill/tokens/css",
        note: "Fifteen elemental identity packs (5 elements × soft/middle/deep). Not a second style-axis brand.",
        packs,
      },
      null,
      2,
    ) + "\n",
  );
  writeFileSync(
    join(dist, "apply-brand-pack.js"),
    `const PACKS = ${JSON.stringify(packs, null, 2)};

export function listBrandPacks() {
  return PACKS.slice();
}

export function resolveBrandPack(input) {
  if (input == null || input === "") return null;
  if (typeof input === "object") {
    return (
      PACKS.find((p) => p.element === input.element && (
        input.name ? p.name === input.name : input.intensity ? p.intensity === input.intensity : p.intensity === "middle"
      )) || null
    );
  }
  const key = String(input);
  return (
    PACKS.find((p) => p.name === key) ||
    PACKS.find((p) => p.element + ":" + p.intensity === key) ||
    PACKS.find((p) => p.element === key && p.intensity === "middle") ||
    null
  );
}

export function applyBrandPack(input, root) {
  const pack = resolveBrandPack(input);
  if (!pack || !root || typeof root.setAttribute !== "function") return null;
  root.setAttribute("data-cs-element", pack.element);
  if (pack.intensity === "middle") root.removeAttribute("data-cs-variant");
  else root.setAttribute("data-cs-variant", pack.name);
  return pack;
}
`,
  );
  writeFileSync(
    join(dist, "apply-brand-pack.d.ts"),
    `export type BrandPack = {\n  element: string;\n  intensity: "soft" | "middle" | "deep";\n  name: string;\n  label: string;\n};\nexport function listBrandPacks(): BrandPack[];\nexport function resolveBrandPack(input: string | { element: string; intensity?: string; name?: string } | null | undefined): BrandPack | null;\nexport function applyBrandPack(input: string | { element: string; intensity?: string; name?: string }, root: { setAttribute: Function; removeAttribute: Function }): BrandPack | null;\n`,
  );
  writeIndex(join(root, "packages/themes"), [
    "export {",
    "  ThemeProvider,",
    "  useTheme,",
    "  getThemeInitScript,",
    "  resolveTheme,",
    "  THEME_VALUES,",
    "  CONTRAST_VALUES,",
    "  DENSITY_VALUES,",
    "} from \"./dist/provider.js\";",
    "export { applyBrandPack, resolveBrandPack, listBrandPacks } from \"./dist/apply-brand-pack.js\";",
  ]);
  writeFileSync(
    join(root, "packages/themes/index.d.ts"),
    `export {\n  ThemeProvider,\n  useTheme,\n  getThemeInitScript,\n  resolveTheme,\n  THEME_VALUES,\n  CONTRAST_VALUES,\n  DENSITY_VALUES,\n} from "./dist/provider";\nexport type * from "./dist/provider";\nexport { applyBrandPack, resolveBrandPack, listBrandPacks } from "./dist/apply-brand-pack";\nexport type { BrandPack } from "./dist/apply-brand-pack";\n`,
  );
}

async function buildIcons() {
  const dist = join(root, "packages/icons/dist");
  resetDir(dist);
  await bundleOne(join(root, "components/icon/Icon.jsx"), join(dist, "Icon.js"));
  writeIndex(join(root, "packages/icons"), [
    "export { Icon, CS_ICONS } from \"./dist/Icon.js\";",
  ]);
}

async function buildPrimitives() {
  const dist = join(root, "packages/primitives/dist");
  resetDir(dist);
  await bundleOne(join(root, "components/_utils/sanitize-html.js"), join(dist, "sanitize-html.js"));
  await bundleOne(join(root, "components/overlays/OverlayManager.jsx"), join(dist, "overlay.js"));
  await bundleOne(join(root, "packages/primitives/src/telemetry.js"), join(dist, "telemetry.js"));
  await bundleOne(join(root, "components/_utils/roving.js"), join(dist, "collection.js"));
  writeIndex(join(root, "packages/primitives"), [
    "export {",
    "  focusableSelector,",
    "  attachFocusTrap,",
    "  applySiblingInert,",
    "  getOverlayManager,",
    "  useOverlayLayer,",
    "} from \"./dist/overlay.js\";",
    "export { sanitizeHtml, isAllowedUrl } from \"./dist/sanitize-html.js\";",
    "export { reportAdoption, reportDeprecation } from \"./dist/telemetry.js\";",
    "export { nextRovingIndex, wrapIndex, reduceListbox } from \"./dist/collection.js\";",
  ]);
}

await buildReact();
buildTokens();
await buildThemes();
await buildIcons();
await buildPrimitives();
await import("./build-stable-global.mjs");
console.log("PASS build-workspace-packages");
