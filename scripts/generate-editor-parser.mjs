// Generate the same inert HTML parser for Node, bundler and no-build consumers.
// Do not hand-edit the output. Dependencies are pinned in package-lock.json.
import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(readFileSync(resolve(root, 'package-lock.json'), 'utf8'));
const provenance = Object.fromEntries(['parse5', 'entities', 'esbuild'].map(name => {
  const pkg = lock.packages[`node_modules/${name}`];
  if (!pkg?.version || !pkg?.integrity) throw new Error(`Missing locked provenance: ${name}`);
  return [name, { version: pkg.version, integrity: pkg.integrity }];
}));
const parserLicenses = Object.fromEntries(['parse5', 'entities'].map(name => {
  const license = lock.packages[`node_modules/${name}`]?.license;
  if (typeof license !== 'string' || !license.trim()) throw new Error(`Missing locked license: ${name}`);
  return [name, license];
}));
const { outputFiles } = buildSync({
  absWorkingDir: root,
  stdin: { contents: "export { parseFragment } from 'parse5';", resolveDir: root },
  bundle: true, write: false, format: 'iife', globalName: 'editorParser',
  minify: true, target: 'es2020', charset: 'utf8', legalComments: 'none',
});
const text = `// GENERATED by scripts/generate-editor-parser.mjs. Do not edit.\n` +
  `// parse5: ${parserLicenses.parse5}; entities: ${parserLicenses.entities}. Full notices: _vendor/editor-parser/NOTICE.txt.\n` +
  `// Locked provenance: ${JSON.stringify(provenance)}\n` +
  `export const parseEditorFragment = (() => {\n${outputFiles[0].text}\nreturn editorParser.parseFragment;\n})();\n`;
const path = resolve(root, 'components/forms/editor-parser.js');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text) throw new Error('Editor parser stale; run npm run build:editor-parser');
  console.log('PASS editor parser provenance and generated bytes');
} else {
  writeFileSync(path, text);
  console.log(`Generated editor parser (${Buffer.byteLength(text)} bytes)`);
}
