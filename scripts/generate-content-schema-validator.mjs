import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {buildSync} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const schema=JSON.parse(readFileSync(new URL('../templates/schema/content-schema.schema.json',import.meta.url)));
const ajv=new Ajv({strict:true,allErrors:true,code:{source:true,esm:true}});
const code=standaloneCode(ajv,ajv.compile(schema));
const bundle=buildSync({stdin:{contents:code,resolveDir:root},bundle:true,write:false,format:'esm',minify:true,target:'es2020'}).outputFiles[0].text;
const lock=JSON.parse(readFileSync(new URL('../package-lock.json',import.meta.url)));
const text='// GENERATED by scripts/generate-content-schema-validator.mjs.\n// Ajv runtime helper: MIT; see ../vendor/ajv-LICENSE.\n// Ajv '+lock.packages['node_modules/ajv'].version+' '+lock.packages['node_modules/ajv'].integrity+'\n'+bundle+'\nexport const sourceSchema = '+JSON.stringify(schema)+';\n';
const output=new URL('../_audit/lib/content-schema-validator.mjs',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(output,'utf8')!==text)throw Error('Stale content schema validator');}else writeFileSync(output,text);
console.log('PASS compiled draft-07 content-schema validator; no runtime compilation');
