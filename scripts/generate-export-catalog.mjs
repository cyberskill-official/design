#!/usr/bin/env node
// Reconcile the public source-derived bundle exports, manifest and legacy ESM.
// Lifecycle/kind decisions remain explicit authoring data; never infer stability.
import {readFileSync,writeFileSync} from 'node:fs';
import {buildBundle,REPO_ROOT} from './build-bundle.mjs';
import {join} from 'node:path';
import {validateLegacyExportSection,stampLegacyVersionComment} from './lib/legacy-export-section.mjs';
import {deriveCardMetadata} from './lib/card-metadata.mjs';
const read=p=>readFileSync(join(REPO_ROOT,p),'utf8');
const manifest=JSON.parse(read('_ds_manifest.json')),life=JSON.parse(read('components/lifecycle.json'));
const catalog=JSON.parse(read('scripts/catalog-source.json'));
for(const key of ['namespace','startingPoints','templates','hasThumbnailHtml','themes','brandFonts','source'])manifest[key]=catalog[key];
const {header}=buildBundle();
const names=new Set();
const exports=header.components.map(entry=>{
 if(names.has(entry.name))throw Error('Duplicate exposed export '+entry.name);
 names.add(entry.name);
 const metadata=life.components[entry.name];
 if(!metadata||!['component','constant','hook'].includes(metadata.kind)||metadata.sourcePath!==entry.sourcePath)throw Error('Missing or mismatched export kind/source contract: '+entry.name);
 const registeredHook=(catalog.publicHooks||[]).some(hook=>hook.name===entry.name&&hook.sourcePath===entry.sourcePath);
 if((metadata.kind==='hook')!==registeredHook)throw Error('Public hook kind/membership mismatch: '+entry.name);
 return {...entry,kind:metadata.kind};
}).sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0);
const orphan=Object.keys(life.components).filter(name=>!names.has(name));
if(orphan.length)throw Error('Orphan lifecycle entries: '+orphan.join(', '));
manifest.schemaVersion=1;
manifest.components=exports;
manifest.cards=deriveCardMetadata(catalog.cards,read);
const version=read('VERSION').trim(),legacy=read('_esm/cs.mjs');
const at=legacy.indexOf('export const VERSION =');
if(at<0)throw Error('Missing legacy bootstrap boundary');
validateLegacyExportSection(legacy.slice(at));
const prefix=stampLegacyVersionComment(legacy.slice(0,at),version).replace('GENERATED from _ds_manifest.json','GENERATED by scripts/generate-export-catalog.mjs');
const outputs={
 '_ds_manifest.json':(JSON.stringify(manifest,null,2)+'\n').replace(/[\u0080-\uffff]/g,c=>'\\u'+c.charCodeAt(0).toString(16).padStart(4,'0')),
 '_esm/cs.mjs':prefix+`export const VERSION = "${version}";\n`+exports.map(e=>`export const ${e.name} = CS.${e.name};`).join('\n')+'\n',
};
let stale=false;
for(const [path,text] of Object.entries(outputs)){
 if(process.argv.includes('--check')){if(read(path)!==text){console.error('Stale export catalog: '+path);stale=true;}}
 else writeFileSync(join(REPO_ROOT,path),text);
}
if(stale)process.exitCode=1;
else console.log(`${process.argv.includes('--check')?'PASS':'Generated'} export catalog: ${exports.length} public exports, ${exports.filter(e=>e.kind==='component').length} components and ${exports.filter(e=>e.kind==='constant').length} constants and ${exports.filter(e=>e.kind==='hook').length} hooks`);
