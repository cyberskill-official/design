import assert from 'node:assert/strict';
import { readdirSync, lstatSync } from 'node:fs';
import { join, posix } from 'node:path';
import { parse } from '@babel/parser';
import { sourceComponentFunctions } from './component-export.mjs';
import { componentCssReader, readComponentCssGraph, sourceSha } from './component-css-graph.mjs';
import { componentSourceAnalysis } from './component-css-sources.mjs';
const producers = ['package-lock.json', 'scripts/generate-component-css-entries.mjs', 'scripts/lib/component-css-entries.mjs', 'scripts/lib/component-css-graph.mjs', 'scripts/lib/component-css-sources.mjs', 'scripts/lib/component-export.mjs'];

/** Whole-sheet projection. Never edits or removes a declaration or selector. */
export function buildComponentCssEntries(root) {
  const reader = componentCssReader(root);
  producers.forEach(path => reader.read(path));
  const api = JSON.parse(reader.read('components/api-index.json'));
  const exports = api.exports.filter(entry => entry.kind === 'component');
  const names = exports.map(entry => entry.name);
  assert(names.length && new Set(names).size === names.length, 'Ambiguous component export membership');
  const independent = [];
  function census(directory) {
    for (const name of readdirSync(join(reader.root, directory)).sort()) {
      const path = directory + '/' + name;
      const stat = lstatSync(join(reader.root, path));
      assert(!stat.isSymbolicLink(), 'Component source census symlink: ' + path);
      if (stat.isDirectory()) census(path);else if (name.endsWith('.jsx')) {
        const ast = parse(reader.read(path), {
          sourceType: 'module',
          plugins: ['jsx']
        });
        for (const name of sourceComponentFunctions(ast)) independent.push({
          name,
          sourcePath: path
        });
      }
    }
  }
  census('components');
  const membership = rows => rows.map(({
    name,
    sourcePath
  }) => name + ':' + sourcePath).sort();
  assert.deepEqual(membership(exports), membership(independent), 'API component source membership is stale');
  for (const entry of exports) {
    assert(/^[A-Z][A-Za-z0-9]*$/.test(entry.name), 'Unsafe component entry name');
    assert.equal(sourceSha(reader.read(entry.sourcePath)), entry.sourceSha256, 'API source hash is stale: ' + entry.name);
  }
  const graph = readComponentCssGraph(reader);
  const analysis = componentSourceAnalysis(reader, graph);
  const components = {};
  for (const entry of exports) {
    const evidence = analysis.analyze(entry.sourcePath);
    const owners = evidence.hooks.flatMap(name => [...(graph.classes.get(name) || [])]);
    const sheets = evidence.fallbacks.length ? [...graph.order] : graph.close(owners);
    components[entry.name] = {
      sourcePath: entry.sourcePath,
      entry: 'styles/components/' + entry.name + '.css',
      kind: evidence.fallbacks.length ? 'full-fallback' : 'whole-sheet-closure',
      sheets,
      sourceSheetBytes: sheets.reduce((total, path) => total + graph.sheets.get(path).bytes, 0),
      ...evidence
    };
  }
  const manifest = {
    schemaVersion: 1,
    contract: 'Conservative whole-sheet dependency closures, not selector pruning or isolated component styles. Caller children/classes require their own entry or one ordered union. No runtime/support/accessibility certification.',
    sourceOrder: graph.order,
    sharedSheets: graph.order.filter(path => graph.shared.has(path)),
    sharedReasons: graph.sharedReasons,
    assets: graph.assets,
    fullSourceSheetBytes: graph.order.reduce((total, path) => total + graph.sheets.get(path).bytes, 0),
    components,
    sourceInputs: Object.fromEntries([...reader.inputs].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))
  };
  const outputs = new Map();
  function entryCss(sheets) {
    return '/* Generated by scripts/generate-component-css-entries.mjs. Whole sheets; source order preserved. */\n' + sheets.map(path => '@import url("../../' + path + '");').join('\n') + '\n';
  }
  for (const component of Object.values(components)) outputs.set(component.entry, entryCss(component.sheets));
  outputs.set('styles/components/foundation.css', entryCss(manifest.sharedSheets));
  outputs.set('styles/components/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  const table = Object.fromEntries(Object.entries(components).map(([name, row]) => [name, row.sheets]));
  outputs.set('styles/components/compose.mjs', `// Generated whole-sheet union data; no filesystem or browser dependency.\nconst order = ${JSON.stringify(graph.order)};\nconst foundation = ${JSON.stringify(manifest.sharedSheets)};\nconst entries = ${JSON.stringify(table)};\n\n/** Return one deduplicated global-order list. Write a single import manifest. */\nexport function componentStylesheets(names) {\n  if (!Array.isArray(names)) throw new TypeError('Component names must be an array');\n  const selected = new Set(foundation);\n  for (const name of names) {\n    if (typeof name !== 'string' || !Object.hasOwn(entries, name)) throw new Error('Unknown component CSS entry: ' + String(name));\n    entries[name].forEach(path => selected.add(path));\n  }\n  return order.filter(path => selected.has(path));\n}\n`);
  return {
    manifest,
    outputs
  };
}
