import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync } from 'node:fs';
import { resolve, sep, posix } from 'node:path';
import postcss from 'postcss';
import valueParser from 'postcss-value-parser';
export const LAYERS = Object.freeze(['cs-safety', 'cs-reset', 'cs-tokens', 'cs-components', 'cs-accessibility', 'cs-responsive', 'cs-overrides']);
export const SOURCES = Object.freeze(['tokens/fonts.css', 'tokens/colors.css', 'tokens/typography.css', 'tokens/spacing.css', 'tokens/elevation.css', 'tokens/motion.css', 'tokens/component-tokens.css', 'tokens/elements.css', 'tokens/styles.css', 'tokens/theme-attributes.css', 'base/reset.css', 'base/typography.css', 'base/components.css', 'base/forms.css', 'base/feedback.css', 'base/data.css', 'base/navigation.css', 'base/ai.css', 'base/controls.css', 'base/collections.css', 'base/shell.css', 'base/glass.css', 'base/interaction.css', 'base/a11y.css', 'base/responsive.css']);
const sha = value => createHash('sha256').update(value).digest('hex');
export function buildLayeredCss(root, {
  read = path => readFileSync(path, 'utf8'),
  realpath = realpathSync
} = {}) {
  const rootPath = resolve(root),
    inputs = [];
  const load = path => {
    assert(/^(?:styles\.css|(?:tokens|base)\/[a-z0-9-]+\.css)$/.test(path), 'Unsafe CSS source path');
    const absolute = resolve(rootPath, path);
    assert(realpath(absolute).startsWith(realpath(rootPath) + sep), 'CSS source escapes root');
    const text = read(absolute);
    inputs.push({
      path,
      sha256: sha(text)
    });
    return postcss.parse(text, {
      from: path
    });
  };
  const entry = load('styles.css'),
    imports = [];
  entry.each(node => {
    if (node.type === 'comment') return;
    assert(node.type === 'atrule' && node.name === 'import', 'Manifest contains non-import CSS');
    const v = valueParser(node.params).nodes;
    assert(v.length === 1 && v[0].type === 'function' && v[0].value === 'url' && v[0].nodes.length === 1 && v[0].nodes[0].type === 'string', 'Only exact local URL imports are supported');
    imports.push(v[0].nodes[0].value);
  });
  assert.deepEqual(imports, SOURCES, 'Unknown, reordered, duplicate or missing stylesheet source');
  const layers = Object.fromEntries(LAYERS.map(name => [name, postcss.atRule({
    name: 'layer',
    params: name
  })]));
  let importantCount = 0;
  const assets = new Set();
  for (const path of imports) {
    const tree = load(path);
    tree.walkAtRules(rule => {
      assert(!['import', 'layer', 'charset', 'namespace'].includes(rule.name.toLowerCase()), 'Unsupported nested CSS at-rule ' + rule.name + ' in ' + path);
    });
    tree.walkDecls(decl => {
      const v = valueParser(decl.value);
      v.walk(node => {
        if (node.type !== 'function' || node.value.toLowerCase() !== 'url') return;
        assert(node.nodes.length === 1 && ['word', 'string'].includes(node.nodes[0].type), 'Ambiguous CSS URL');
        const url = node.nodes[0].value;
        if (url.startsWith('data:') || url.startsWith('#')) return;
        assert(!/^[a-z]+:|^\/|[?#\\\0]/i.test(url), 'Unsafe or external CSS URL');
        const target = posix.normalize(posix.join(posix.dirname(path), url));
        assert(/^(?:fonts|assets)\/[a-zA-Z0-9_./-]+$/.test(target) && !target.includes('..'), 'CSS URL escapes asset roots');
        assert(realpath(resolve(rootPath, target)).startsWith(realpath(rootPath) + sep), 'CSS asset escapes root');
        node.nodes[0].value = target;
        assets.add(target);
      });
      decl.value = v.toString();
    });
    const important = tree.clone();
    important.walkDecls(decl => {
      if (!decl.important) decl.remove();else importantCount++;
    });
    important.walkComments(n => n.remove());
    prune(important);
    if (important.nodes.length) layers['cs-safety'].append(important.nodes);
    tree.walkDecls(decl => {
      if (decl.important) decl.remove();
    });
    prune(tree);
    const category = path === 'base/reset.css' ? 'cs-reset' : path.startsWith('tokens/') ? 'cs-tokens' : path === 'base/a11y.css' ? 'cs-accessibility' : path === 'base/responsive.css' ? 'cs-responsive' : 'cs-components';
    layers[category].append(postcss.comment({
      text: 'Source: ' + path
    }), ...tree.nodes);
  }
  const output = postcss.root();
  output.append(postcss.comment({
    text: 'Generated by scripts/generate-layered-styles.mjs. Opt-in only; styles.css remains default. Input graph SHA-256 ' + sha(JSON.stringify(inputs))
  }));
  output.append(postcss.atRule({
    name: 'layer',
    params: LAYERS.join(', ')
  }));
  for (const layer of Object.values(layers)) output.append(layer);
  const css = output.toString() + '\n';
  assert(!postcss.parse(css).nodes.some(n => n.type === 'atrule' && n.name === 'import'), 'Residual CSS imports');
  return {
    css,
    manifest: {
      schemaVersion: 1,
      layers: LAYERS,
      inputs,
      assets: [...assets].sort(),
      importantCount,
      sha256: sha(css)
    }
  };
}
function prune(container) {
  for (const node of [...(container.nodes || [])]) {
    if (node.nodes) {
      prune(node);
      if (!node.nodes.length) node.remove();
    }
  }
}
