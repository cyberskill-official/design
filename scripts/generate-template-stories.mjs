#!/usr/bin/env node
/**
 * Generate Storybook CSF for every `_ds_manifest.json` template, grouped like
 * Atomic View (`guidelines/nav-model.cjs`). Run after manifest / template renames:
 *   node scripts/generate-template-stories.mjs
 */
import { writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const require = createRequire(import.meta.url);
const nav = require(join(root, 'guidelines/nav-model.cjs'));
const manifest = require(join(root, '_ds_manifest.json'));

const outDir = join(root, 'stories/Templates/categories');
if (existsSync(outDir)) rmSync(outDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

function exportName(folder) {
  const slug = String(folder || '')
    .split('/')
    .pop()
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim();
  const parts = slug.split(/\s+/).filter(Boolean);
  let name = parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  if (!/^[A-Za-z]/.test(name)) name = `T${name}`;
  return name || 'Template';
}

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
}

const items = (manifest.templates || []).map((t) => ({
  name: t.name,
  entryPath: t.entryPath,
  folder: t.folder,
  shortName: nav.templateShortName(t.name),
  category: nav.classifyTemplate(t.name),
}));

const groups = nav.groupTemplates(items);
let total = 0;

for (const group of groups) {
  const used = new Map();
  const exports = [];
  for (const it of group.items) {
    let key = exportName(it.folder);
    if (used.has(key)) {
      let n = 2;
      while (used.has(`${key}${n}`)) n += 1;
      key = `${key}${n}`;
    }
    used.set(key, true);
    const src = `/${it.entryPath}`;
    exports.push(`
export const ${key} = {
  name: \`${esc(it.shortName)}\`,
  render: () => (
    <IframeSurface src="${esc(src)}" title={\`${esc(it.name)}\`} />
  ),
};`);
    total += 1;
  }

  const body = `/* eslint-disable */
/** AUTO-GENERATED by scripts/generate-template-stories.mjs — do not hand-edit. */
import React from 'react';
import { IframeSurface } from '../../Maintainer/IframeSurface.jsx';

export default {
  title: 'Templates/${esc(group.category)}',
  parameters: {
    layout: 'fullscreen',
    docs: {
      description: {
        component:
          'Design Component starting points from _ds_manifest.json (Atomic View grouping). Portable HTML under templates/.',
      },
    },
  },
};
${exports.join('\n')}
`;
  writeFileSync(join(outDir, `${group.category}.stories.jsx`), body);
}

console.log(
  `generate-template-stories: ${total} templates → ${groups.length} category files in stories/Templates/categories/`,
);
