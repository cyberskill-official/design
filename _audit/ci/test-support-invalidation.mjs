import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {invalidateReviews} from '../../scripts/invalidate-support-reviews.mjs';
const hash = value => createHash('sha256').update(value).digest('hex');
const support = {reviewState:'reviewed',sourceSha256:hash('approved'),reviewedBy:'Reviewer',reviewedAt:'2026-10-17T00:00:00Z',evidence:[{path:'fixture',sha256:hash('approved')}],environments:['fixture'],axes:['fixture'],limitations:[]};
const life = {components:{Fixture:{support:structuredClone(support)}}};
assert.deepEqual(invalidateReviews(life,()=>Buffer.from('approved')),[]);
assert.deepEqual(invalidateReviews(life,()=>Buffer.from('changed')),['Fixture']);
const invalidated = life.components.Fixture.support;
assert.equal(invalidated.reviewState,'unreviewed');
assert.equal(invalidated.reviewedBy,null);
assert.equal(invalidated.sourceSha256,undefined);
assert.equal(invalidated.reviewHistory[0].sourceSha256,support.sourceSha256);
assert.equal(invalidated.reviewedAt,null);
assert.deepEqual(invalidated.reviewHistory[0].evidence,support.evidence,'Approved hashes remain verbatim');
assert.equal(invalidated.reviewHistory[0].reviewedBy,'Reviewer');
assert.deepEqual(invalidated.evidence,[],'New bytes must not inherit old approval');
assert.deepEqual(invalidateReviews(life,()=>Buffer.from('changed')),[],'Invalidation is idempotent');
console.log('PASS support invalidation: unchanged retained; changed invalidated; approval history preserved; no automatic approval');
