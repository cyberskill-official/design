import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {withBrowserFixture} from './lib/browser-fixture.mjs';
execFileSync(process.execPath,['_audit/ci/check-bundle-freshness.mjs'],{stdio:'pipe'});
await withBrowserFixture(async page=>{
 await page.evaluate(()=>{window.calendarChanges=[];window.drawCalendar=value=>renderFixture(React.createElement(CS.Calendar,{value,lang:'en',onChange:d=>calendarChanges.push([d.getFullYear(),d.getMonth(),d.getDate()])}));drawCalendar(0)});
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'January 1970','Timestamp zero is a valid selected date');
 assert.equal(await page.locator('.cs-cal__grid [aria-pressed="true"]').textContent(),'1');
 await page.evaluate(()=>drawCalendar(new Date(2024,1,29)));
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'February 2024','External selected month becomes visible');
 assert.equal(await page.locator('.cs-cal__grid button').count(),29);
 assert.equal(await page.locator('.cs-cal__grid [aria-pressed="true"]').textContent(),'29');
 await page.locator('.cs-cal__head button').last().click();
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'March 2024');
 await page.evaluate(()=>drawCalendar(new Date(2024,1,29)));
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'March 2024','Equivalent parent value does not reset manual navigation');
 await page.locator('.cs-cal__grid button').filter({hasText:/^15$/}).click();
 assert.deepEqual(await page.evaluate(()=>calendarChanges),[[2024,2,15]]);
 assert.equal(await page.locator('.cs-cal__grid [aria-pressed="true"]').count(),0,'Controlled callback does not commit selection');
 await page.evaluate(()=>drawCalendar(new Date(2024,11,31)));
 await page.locator('.cs-cal__head button').last().click();
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'January 2025');
 await page.locator('.cs-cal__head button').first().click();
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'December 2024');
 await page.evaluate(()=>drawCalendar('invalid-date'));
 assert.equal(await page.locator('.cs-cal__grid [aria-pressed="true"]').count(),0);
 assert.equal(await page.locator('.cs-cal__head b').textContent(),'December 2024','Invalid selection preserves navigable view');
 await page.evaluate(()=>{const date=new Date(0);date.setFullYear(0,1,1);date.setHours(0,0,0,0);drawCalendar(date)});
 await page.waitForFunction(()=>document.querySelector('.cs-cal__head b').textContent==='February 0');
 assert.equal(await page.locator('.cs-cal__grid button').count(),29,'Year zero is a Gregorian leap year, not 1900');
 await page.locator('.cs-cal__grid button').filter({hasText:/^29$/}).click();
 assert.deepEqual(await page.evaluate(()=>calendarChanges.at(-1)),[0,1,29],'Emitted year must match displayed year');
 await page.evaluate(()=>{const date=new Date(0);date.setFullYear(99,0,1);drawCalendar(date)});
 await page.waitForFunction(()=>document.querySelector('.cs-cal__head b').textContent==='January 99');
 await page.locator('.cs-cal__grid button').filter({hasText:/^1$/}).click();
 assert.deepEqual(await page.evaluate(()=>calendarChanges.at(-1)),[99,0,1]);
 await page.locator('.cs-cal__grid button').filter({hasText:/^1$/}).focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.evaluate(()=>document.activeElement?.textContent),'2');
 await page.keyboard.press('ArrowDown');
 assert.equal(await page.evaluate(()=>document.activeElement?.textContent),'9');
 await page.keyboard.press('End');
 assert.equal(await page.evaluate(()=>document.activeElement?.textContent),'31');
 await page.keyboard.press('Home');
 assert.equal(await page.evaluate(()=>document.activeElement?.textContent),'1');
 console.log('PASS Calendar: epoch zero, external month updates, leap year, controlled callbacks, keyboard grid navigation and year navigation');
},{browserName:process.env.CS_TEST_BROWSER||'chromium',contextOptions:{timezoneId:'UTC'}});
