import assert from 'node:assert/strict';
import { mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync,symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { summarizeFiles,readInventory,verifyWebsite,portableRuntimeCosts,assertCurrentInventory } from '../../scripts/measure-distribution-costs.mjs';
import { syncTemplateRuntimes } from '../../scripts/sync-support-runtime.mjs';

const root=mkdtempSync(join(tmpdir(),'cs-distribution-test-'));
const write=(path,bytes)=>writeFileSync(join(root,path),bytes);
try {
  for(const dir of ['web','scripts/template-runtime','templates/_vendor','templates/first','templates/second'])mkdirSync(join(root,dir),{recursive:true});
  write('web/index.html','Xin chào'); write('web/app.js','window.x=1;');
  const web=readInventory(join(root,'web'),['index.html','app.js']);
  assertCurrentInventory(join(root,'web'),web);
  assert.equal(web.bodyBytes,Buffer.byteLength('Xin chào')+Buffer.byteLength('window.x=1;'),'Count UTF-8 bytes, not characters');
  assert.deepEqual(summarizeFiles([...web.files].reverse()),web,'Stable ordering');
  for(const rows of [[],[web.files[0],web.files[0]],[{...web.files[0],path:'../escape'}],[{...web.files[0],bytes:-1}],[{...web.files[0],sha256:'invalid'}]])assert.throws(()=>summarizeFiles(rows));
  const manifest={schemaVersion:1,files:web.files};
  write('web/public-site-manifest.json',JSON.stringify(manifest));
  assert.equal(verifyWebsite(join(root,'web'),manifest).bodyBytes,web.bodyBytes+Buffer.byteLength(JSON.stringify(manifest)),'Include manifest bytes in total');
  write('web/app.js','window.x=2;');
  assert.throws(()=>assertCurrentInventory(join(root,'web'),web),/changed during measurement/);
  assert.throws(()=>verifyWebsite(join(root,'web'),manifest),/Website bytes changed/,'Same-size modification is rejected');
  write('web/app.js','window.x=1;');write('web/new.js','new file');
  assert.throws(()=>assertCurrentInventory(join(root,'web'),web,['index.html','app.js','new.js']),/changed during measurement/);
  assert.throws(()=>verifyWebsite(join(root,'web'),manifest),/membership changed/);
  rmSync(join(root,'web/new.js'));rmSync(join(root,'web/app.js'));
  assert.throws(()=>verifyWebsite(join(root,'web'),manifest),/membership changed/);
  symlinkSync(join(root,'web/index.html'),join(root,'web/app.js'));
  assert.throws(()=>verifyWebsite(join(root,'web'),manifest),/symlink/);
  assert.throws(()=>readInventory(join(root,'web'),['../web/index.html']),/Unsafe/);
  write('_ds_manifest.json',JSON.stringify({templates:[{folder:'templates/second'},{folder:'templates/first'}]}));
  write('templates/_vendor/support.js','window.support=true;');write('scripts/template-runtime/ds-base.js','window.base=true;');
  syncTemplateRuntimes(root);
  const paths=['templates/_vendor/support.js','scripts/template-runtime/ds-base.js',...['first','second'].flatMap(folder=>['support.js','ds-base.js'].map(name=>`templates/${folder}/${name}`))];
  const inventory=readInventory(root,paths);
  const portable=portableRuntimeCosts(root,{checkout:inventory,npm:readInventory(root,paths.filter(path=>!path.startsWith('scripts/')))});
  assert.equal(portable.requiredCopies,4);assert.equal(portable.distributions.checkout.generatedRuntimeFiles,4);
  assert.equal(portable.templates.length,2);assert(portable.templates.every(item=>item.runtimeSharePercent===100));
  assert.deepEqual(portable.distributions.npm.canonicalSourceFiles,['templates/_vendor/support.js']);
  assert.match(portable.canonical.find(item=>item.name==='support.js').repositoryRole,/authored source binding not recorded/);
  assert.equal(portable.canonical.find(item=>item.name==='support.js').sourceOriginState,undefined);
  mkdirSync(join(root,'scripts/template-runtime/primitives'),{recursive:true});
  const producer='scripts/build-template-primitives.mjs';write(producer,'// fixture generator');
  const entries=Object.entries({'support.js':'templates/_vendor/support.js','deck-stage.js':'templates/_vendor/deck-stage.js','image-slot.js':'image-slot.js'}).map(([name,output])=>{
    const input='scripts/template-runtime/primitives/'+name,content='// fixture '+name+'\n',generated='// Generated from '+input+' by '+producer+'.\n'+content;
    write(input,content);write(output,generated);return {input,output};
  });
  syncTemplateRuntimes(root);const authoredInventory=readInventory(root,paths);
  const authored=portableRuntimeCosts(root,{checkout:authoredInventory}).canonical.find(item=>item.name==='support.js');
  assert.match(authored.repositoryRole,/local authored compatibility candidate; distribution review pending/);
  assert.equal(authored.sourceOriginState,'generated_from_repository_source_candidate_pending_distribution_review');
  assert(authored.sourceOriginEvidence.includes('scripts/template-runtime/primitives/support.js'));
  const source=readFileSync(join(root,entries[0].input));write(entries[0].input,'changed source');
  assert.throws(()=>portableRuntimeCosts(root,{checkout:authoredInventory}),/not generated from its recorded source/,'Altered source must be rejected');
  write(entries[0].input,source);
  write('templates/first/support.js','drift');
  assert.throws(()=>portableRuntimeCosts(root,{checkout:inventory}),/Stale or missing/,'Measurement must not certify nonreproducible copies');
  assert.equal(readFileSync(join(root,'templates/first/support.js'),'utf8'),'drift','Measurement does not repair sources');
} finally {rmSync(root,{recursive:true,force:true});}
const current=portableRuntimeCosts(process.cwd(),{source:readInventory(process.cwd(),['_ds_manifest.json','templates/_vendor/support.js','scripts/template-runtime/ds-base.js'])});
assert.equal(current.requiredCopies,170);assert.equal(current.templates.length,85);
console.log('PASS distribution measurements: UTF-8 byte counts, deterministic membership, altered/missing/added/linked webroot rejection, read-only runtime identity, verified authored origin and altered-binding rejection, and all 85 source folders');
