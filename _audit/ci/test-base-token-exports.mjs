import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {collectTokenDeclarations} from '../../scripts/lib/token-declarations.mjs';
import {projectBaseTokens, baseExportExclusions} from '../../scripts/lib/base-token-exports.mjs';

const graph = collectTokenDeclarations(process.cwd());
const inventory = JSON.parse(readFileSync('tokens/tokens.json', 'utf8'));
assert.deepEqual(projectBaseTokens(graph, inventory), inventory);
for (const role of ['success','danger','warning','info']) assert.ok(Object.hasOwn(inventory.root.color, `--cs-color-semantic-${role}-text`), 'Explicit additional semantic text inventory role');
assert.equal(Object.values(inventory.root).reduce((n, group) => n + Object.keys(group).length, 0), 175);
assert.equal(Object.keys(baseExportExclusions).length, 9);
const changed = structuredClone(graph);
const spacing = changed.declarations.find(d => d.name === '--cs-space-2' && d.context[0].selector === ':root');
assert.ok(spacing);
spacing.value = '9px';
const output = projectBaseTokens(changed, inventory);
assert.equal(Object.values(output.root).find(group => '--cs-space-2' in group)['--cs-space-2'], '9px');
assert.equal(inventory.root.density['--cs-density-space-2'], 'var(--cs-space-2)', 'Aliases remain expressions, not flattened literals');
assert.deepEqual(output.themes, inventory.themes, 'Base projection does not rewrite conditional scopes');
const missing = structuredClone(graph);
missing.declarations = missing.declarations.filter(d => d.name !== '--cs-space-2');
assert.throws(() => projectBaseTokens(missing, inventory), /Missing unconditional root source/);
const extra = structuredClone(graph);
extra.declarations.push({...spacing, name: '--cs-unclassified'});
assert.throws(() => projectBaseTokens(extra, inventory), /Unclassified root token/);
const duplicate = structuredClone(graph);
duplicate.declarations.push({...spacing});
assert.throws(() => projectBaseTokens(duplicate, inventory), /Ambiguous root token/);
const conditional = structuredClone(graph);
conditional.declarations.push({...spacing, value: '99px', context: [{kind: 'at-rule', name: 'media', params: '(prefers-contrast: more)'}, {kind: 'rule', selector: ':root'}]});
assert.deepEqual(projectBaseTokens(conditional, inventory), inventory, 'Conditional roots must never become unconditional defaults');
console.log('PASS base export source parity: 175 typed roots, nine explicit exclusions, source mutation, missing/extra/duplicate and conditional-root guards.');
